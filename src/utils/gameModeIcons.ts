const VERIFIED_IDS = new Set(Object.values(GAME_MODE_ICON_IDS));

export function getGameModeIconUrl(mode: string | null | undefined): string | null {
  if (!mode) return null;
  const id = GAME_MODE_ICON_IDS[mode.trim().toLowerCase()];
  return id ? `https://cdn.brawlify.com/game-modes/regular/${id}.png` : null;
}

export function getGameModeIconUrlById(id: number | null | undefined): string | null {
  return typeof id === "number" && VERIFIED_IDS.has(id)
    ? `https://cdn.brawlify.com/game-modes/regular/${id}.png` : null;
}
