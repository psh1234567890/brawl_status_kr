import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const API_BASE_URL = "https://api.brawlapi.com/v2/raw";
const USER_AGENT = "brawl-status-kr/1.0";
const outputPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/constants/generatedBrawlJapaneseTranslations.ts",
);

async function getGameFile(path) {
  const response = await fetch(`${API_BASE_URL}/${path}`, {
    headers: { "User-Agent": USER_AGENT },
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch ${path}: ${response.status}`);
  }

  const json = await response.json();
  return json.data;
}

function getTranslation(texts, tid, key) {
  return tid ? texts[tid]?.[key] ?? null : null;
}

function lowerFirst(value) {
  return value ? value[0].toLowerCase() + value.slice(1) : value;
}

function toTitleCase(value) {
  return value
    ? value.toLowerCase().replace(/\b[a-z]/g, (letter) => letter.toUpperCase())
    : value;
}

function addAlias(record, key, value) {
  if (key && value) record[key] = value;
}

function sortRecord(record) {
  return Object.fromEntries(
    Object.entries(record).sort(([left], [right]) => left.localeCompare(right)),
  );
}

function toTsRecord(name, value) {
  return `export const ${name}: Record<string, string> = ${JSON.stringify(
    sortRecord(value),
    null,
    2,
  )};`;
}

const [englishTexts, japaneseTexts, characters, locations, modeVariations] =
  await Promise.all([
    getGameFile("localization/texts"),
    getGameFile("localization/jp"),
    getGameFile("csv_logic/characters"),
    getGameFile("csv_logic/locations"),
    getGameFile("csv_logic/game_mode_variations"),
  ]);

const japaneseMapDict = {};
const englishModeDict = {};
const japaneseModeDict = {};
const englishModeDisplayDict = {};
const japaneseModeDisplayDict = {};
const japaneseBrawlerDict = {};

for (const mode of Object.values(modeVariations)) {
  const englishName = getTranslation(englishTexts, mode.TID, "EN");
  const japaneseName = getTranslation(japaneseTexts, mode.TID, "JP");
  if (!englishName) continue;

  const modeKey = mode.Name === "Showdown" ? "soloShowdown" : lowerFirst(mode.Name);
  const englishDisplay = englishName;
  const japaneseDisplay = japaneseName ?? englishName;

  addAlias(englishModeDisplayDict, mode.Name, englishDisplay);
  addAlias(englishModeDisplayDict, mode.ShortName, englishDisplay);
  addAlias(englishModeDisplayDict, modeKey, englishDisplay);
  addAlias(englishModeDisplayDict, englishName, englishDisplay);
  addAlias(englishModeDisplayDict, toTitleCase(englishName), englishDisplay);

  addAlias(japaneseModeDisplayDict, mode.Name, japaneseDisplay);
  addAlias(japaneseModeDisplayDict, mode.ShortName, japaneseDisplay);
  addAlias(japaneseModeDisplayDict, modeKey, japaneseDisplay);
  addAlias(japaneseModeDisplayDict, englishName, japaneseDisplay);
  addAlias(japaneseModeDisplayDict, toTitleCase(englishName), japaneseDisplay);

  if (!mode.Disabled) {
    englishModeDict[modeKey] = englishDisplay;
    japaneseModeDict[modeKey] = japaneseDisplay;
  }
}

for (const location of Object.values(locations)) {
  const englishName = getTranslation(englishTexts, location.TID, "EN");
  const japaneseName = getTranslation(japaneseTexts, location.TID, "JP");
  if (englishName && japaneseName) japaneseMapDict[englishName] = japaneseName;
}

for (const character of Object.values(characters)) {
  const englishName = getTranslation(englishTexts, character.TID, "EN");
  const japaneseName = getTranslation(japaneseTexts, character.TID, "JP");
  if (!englishName || character.Disabled || !character.ItemName || !japaneseName) continue;

  japaneseBrawlerDict[englishName.toUpperCase()] = japaneseName;
  japaneseBrawlerDict[englishName] = japaneseName;
}

const source = `// Generated by scripts/update-brawl-japanese-translations.mjs.
// Do not edit manually. Run: npm run translations:ja:update

${toTsRecord("generatedJapaneseMapDict", japaneseMapDict)}

${toTsRecord("generatedEnglishModeDict", englishModeDict)}

${toTsRecord("generatedJapaneseModeDict", japaneseModeDict)}

${toTsRecord("generatedEnglishModeDisplayDict", englishModeDisplayDict)}

${toTsRecord("generatedJapaneseModeDisplayDict", japaneseModeDisplayDict)}

${toTsRecord("generatedJapaneseBrawlerDict", japaneseBrawlerDict)}
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");

console.log(
  `Generated ${Object.keys(japaneseMapDict).length} Japanese maps, ${Object.keys(japaneseModeDict).length} Japanese modes, ${Object.keys(japaneseBrawlerDict).length} Japanese brawler aliases.`,
);
