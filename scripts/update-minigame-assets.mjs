import { readFile, rename, unlink, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const BRAWLIFY_CDN_REPOSITORY = "Brawlify/CDN";
const githubBase = "https://api.github.com/repos/" + BRAWLIFY_CDN_REPOSITORY;
const outputPath = resolve(dirname(fileURLToPath(import.meta.url)), "../src/constants/generatedBrawlerModels.ts");

export function parseModelTree(treeResponse, commitSha) {
  if (!/^[0-9a-f]{40}$/i.test(commitSha)) throw new Error("Invalid CDN source commit SHA");
  if (!treeResponse || typeof treeResponse !== "object" || treeResponse.truncated !== false || !Array.isArray(treeResponse.tree)) {
    throw new Error("Invalid or truncated GitHub tree response");
  }
  const assets = [];
  const seen = new Set();
  for (const item of treeResponse.tree) {
    if (typeof item?.path !== "string" || item.type !== "blob") continue;
    const match = /^brawlers\/model\/([0-9]+)\.png$/.exec(item.path);
    if (!match) continue;
    const brawlerId = Number(match[1]);
    if (!Number.isSafeInteger(brawlerId) || brawlerId <= 0 || seen.has(brawlerId)) {
      throw new Error("Invalid or duplicate brawler model ID");
    }
    if (typeof item.sha !== "string" || !/^[0-9a-f]{40}$/i.test(item.sha)) {
      throw new Error("Invalid Git blob SHA for " + item.path);
    }
    seen.add(brawlerId);
    assets.push({ brawlerId, path: item.path, blobSha: item.sha.toLowerCase() });
  }
  if (assets.length === 0) throw new Error("GitHub tree contains no brawler model images");
  return assets.sort((left, right) => left.brawlerId - right.brawlerId);
}

export function formatModelManifest(commitSha, assets) {
  if (!/^[0-9a-f]{40}$/i.test(commitSha)) throw new Error("Invalid CDN source commit SHA");
  const sorted = [...assets].sort((left, right) => left.brawlerId - right.brawlerId);
  const seen = new Set();
  for (const asset of sorted) {
    const pathMatch = /^brawlers\/model\/([0-9]+)\.png$/.exec(asset.path);
    if (!Number.isSafeInteger(asset.brawlerId) || asset.brawlerId <= 0 || seen.has(asset.brawlerId) ||
      !pathMatch || Number(pathMatch[1]) !== asset.brawlerId || !/^[0-9a-f]{40}$/i.test(asset.blobSha)) {
      throw new Error("Invalid brawler model manifest entry");
    }
    seen.add(asset.brawlerId);
  }
  if (sorted.length === 0) throw new Error("Cannot generate an empty brawler model manifest");
  const source = JSON.stringify(sorted, null, 2);
  return [
    "// Generated by scripts/update-minigame-assets.mjs. Do not edit manually.",
    "// Source: https://github.com/" + BRAWLIFY_CDN_REPOSITORY + " at " + commitSha.toLowerCase(),
    "// Update with: npm run minigames:assets:update",
    "export type BrawlerModelAsset = { brawlerId: number; path: string; blobSha: string };",
    "export const brawlerModelSource = { repository: \"" + BRAWLIFY_CDN_REPOSITORY + "\", commitSha: \"" + commitSha.toLowerCase() + "\" } as const;",
    "export const generatedBrawlerModels: readonly BrawlerModelAsset[] = " + source + ";",
    "",
  ].join("\n");
}

async function getJson(url, fetchImpl) {
  const response = await fetchImpl(url, { headers: { Accept: "application/vnd.github+json", "User-Agent": "brawl-status-kr-minigame-assets" } });
  if (!response.ok) throw new Error("GitHub returned HTTP " + response.status + " for " + url);
  return response.json();
}

export async function updateModelManifest({ fetchImpl = fetch, target = outputPath } = {}) {
  const commit = await getJson(githubBase + "/commits/master", fetchImpl);
  const commitSha = commit?.sha;
  if (typeof commitSha !== "string" || !/^[0-9a-f]{40}$/i.test(commitSha)) throw new Error("GitHub returned an invalid master commit");
  const treeResponse = await getJson(githubBase + "/git/trees/" + commitSha + "?recursive=1", fetchImpl);
  const assets = parseModelTree(treeResponse, commitSha);
  const content = formatModelManifest(commitSha, assets);
  let previous = null;
  try { previous = await readFile(target, "utf8"); } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (previous === content) return { changed: false, count: assets.length, commitSha };
  const temporaryPath = target + "." + process.pid + ".tmp";
  try {
    await writeFile(temporaryPath, content, "utf8");
    await rename(temporaryPath, target);
  } catch (error) {
    await unlink(temporaryPath).catch(() => {});
    throw error;
  }
  return { changed: true, count: assets.length, commitSha };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  updateModelManifest()
    .then(({ changed, count, commitSha }) => {
      console.log((changed ? "Updated" : "Already current") + " " + count + " Brawlify model paths at " + commitSha + ".");
    })
    .catch((error) => {
      console.error("Could not update the Brawlify model manifest: " + (error instanceof Error ? error.message : String(error)));
      process.exitCode = 1;
    });
}
